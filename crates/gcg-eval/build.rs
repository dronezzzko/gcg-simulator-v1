//! Build script of `gcg-eval`: the code digest of `build-support/digest-manifest.txt`
//! (docs/port/PLAN.md §2.4, X19, W-103), exposed as `env!("GCG_CODE_DIGEST")`, and the deck
//! files of `examples/decks/` and `examples/decks/eval/` embedded as
//! `$OUT_DIR/embedded_decks.rs` (W-123: the named deck sets work from any directory).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

mod code_digest {
    include!("../../build-support/code_digest.rs");
}

/// `(stem, path)` of the `.txt` files of `dir`, by file name; none when `dir` is missing.
fn deck_files(dir: &Path) -> Vec<(String, PathBuf)> {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return Vec::new();
    };
    let mut out: Vec<(String, PathBuf)> = entries
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.is_file() && p.extension().is_some_and(|x| x == "txt"))
        .filter_map(|p| {
            let stem = p.file_stem()?.to_str()?.to_owned();
            Some((stem, p))
        })
        .collect();
    out.sort_by(|a, b| a.1.file_name().cmp(&b.1.file_name()));
    out
}

fn embed_decks(root: &Path) {
    let out_dir = std::env::var_os("OUT_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| panic!("cargo sets OUT_DIR for build scripts"));
    let decks = root.join("examples").join("decks");
    println!("cargo:rerun-if-changed={}", decks.display());
    let mut text = String::from("// Generated by build.rs from examples/decks (W-123).\n");
    for (name, dir) in [("EXAMPLES", decks.clone()), ("EVAL", decks.join("eval"))] {
        let _ = writeln!(text, "pub const {name}: &[(&str, &str)] = &[");
        for (stem, path) in deck_files(&dir) {
            println!("cargo:rerun-if-changed={}", path.display());
            let _ = writeln!(
                text,
                "    ({stem:?}, include_str!({:?})),",
                path.display().to_string()
            );
        }
        text.push_str("];\n");
    }
    std::fs::write(out_dir.join("embedded_decks.rs"), text)
        .unwrap_or_else(|e| panic!("cannot write embedded_decks.rs: {e}"));
}

fn main() {
    let manifest_dir = std::env::var_os("CARGO_MANIFEST_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| panic!("cargo sets CARGO_MANIFEST_DIR for build scripts"));
    let root = manifest_dir.join("..").join("..");
    code_digest::emit(&root);
    embed_decks(&root);
}
