//! `gcg-diff trace-search <trace-id> <decision> [--level 2|3] [--iteration N]` (PLAN §8.7
//! drill-down levels 2-3): run the reference search of one recorded decision on both sides
//! and print the first divergent iteration, then the first divergent apply inside it.
//!
//! Python's records are the trace's own `iter`/`apply_trace` records for that decision when it
//! holds them at the requested level (the committed acceptance searches); otherwise `uv run
//! python oracle/traces.py --deep ID --decision K [--apply-level] [--iteration N]`
//! regenerates them. Rust replays the trace to the decision with the real engine and calls
//! `gcg_ai_reference::search` with the header's preset (`baseline-*` with the baseline
//! weights, `traces.py` `cmd_deep`), the decision's recorded agent seed and the level-2/3
//! [`Recorder`].

use std::path::Path;
use std::process::Command;

use gcg_ai::{AgentCx, DEFAULT_WEIGHTS, Scratch};
use gcg_core::pool::{Cancel, Pool, TaskCx};
use gcg_core::rng::SplitMix64;

use crate::agents::Recorder;
use crate::engine::RealEngine;
use crate::explain::{decision, find_trace, replay_to};
use crate::manifest::Repo;
use crate::replay::action_display;
use crate::{ApplyTraceRec, EngineUnderTest, IterRec, Record};

/// The drill-down request.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Request<'a> {
    pub tier: u8,
    pub file: Option<&'a Path>,
    pub id: &'a str,
    pub decision: u32,
    /// 2 (iterations) or 3 (iterations and applies).
    pub level: u8,
    pub iteration: Option<u32>,
}

/// Python's level-2/3 records of one decision, from the trace or from `traces.py --deep`.
///
/// # Errors
/// The regeneration failed.
pub fn python_records(
    repo: &Repo,
    trace: &crate::Trace,
    req: &Request<'_>,
) -> Result<(Vec<IterRec>, Vec<ApplyTraceRec>, &'static str), String> {
    let wanted = |n: u32| req.iteration.is_none_or(|k| k == n);
    let iters: Vec<IterRec> = trace
        .records
        .iter()
        .filter_map(|r| match r {
            Record::Iter(it) if it.decision == req.decision && wanted(it.iteration.n) => {
                Some(it.clone())
            }
            _ => None,
        })
        .collect();
    let applies: Vec<ApplyTraceRec> = trace
        .records
        .iter()
        .filter_map(|r| match r {
            Record::ApplyTrace(a) if a.decision == req.decision && wanted(a.n) => Some(a.clone()),
            _ => None,
        })
        .collect();
    if !iters.is_empty() && (req.level == 2 || !applies.is_empty()) {
        return Ok((iters, applies, "stored in the trace"));
    }
    let mut cmd = Command::new("uv");
    cmd.args(["run", "python", "oracle/traces.py", "--deep"])
        .arg(req.id)
        .arg("--decision")
        .arg(req.decision.to_string())
        .current_dir(&repo.root);
    if req.level == 3 {
        cmd.arg("--apply-level");
    }
    if let Some(n) = req.iteration {
        cmd.arg("--iteration").arg(n.to_string());
    }
    let out = cmd
        .output()
        .map_err(|e| format!("traces.py --deep needs uv, which could not run: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "traces.py --deep failed: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        ));
    }
    let text = String::from_utf8_lossy(&out.stdout);
    let mut iters = Vec::new();
    let mut applies = Vec::new();
    for line in text.lines().filter(|l| !l.is_empty()) {
        match crate::reader::parse_record(line)? {
            Record::Iter(it) => iters.push(it),
            Record::ApplyTrace(a) => applies.push(a),
            other => return Err(format!("traces.py --deep printed {other:?}")),
        }
    }
    Ok((iters, applies, "regenerated by traces.py --deep"))
}

/// Rust's level-2/3 records of one decision.
///
/// # Errors
/// The trace has no search at the decision, or the replay or the search failed.
pub fn rust_records(
    trace: &crate::Trace,
    req: &Request<'_>,
) -> Result<(Vec<IterRec>, Vec<ApplyTraceRec>), String> {
    let d = decision(trace, req.decision)?;
    let block = d
        .agent
        .as_ref()
        .filter(|a| a.iterations.is_some())
        .ok_or_else(|| format!("decision {} has no recorded search", req.decision))?;
    let preset = trace
        .header
        .preset
        .as_deref()
        .ok_or_else(|| "the header names no preset".to_owned())?;
    let (cfg, weights) = match preset.strip_prefix("baseline-") {
        Some(p) => (
            gcg_ai_reference::baseline_preset(p),
            gcg_ai_reference::BASELINE_WEIGHTS,
        ),
        None => (gcg_ai_reference::reference_preset(preset), DEFAULT_WEIGHTS),
    };
    let cfg = cfg.ok_or_else(|| format!("no reference preset {preset:?}"))?;
    let mut engine = RealEngine::for_trace(&trace.header);
    replay_to(trace, req.decision, &mut engine)?;
    let st = engine
        .state()
        .ok_or_else(|| "the replay holds no state".to_owned())?;
    let mut rec = Recorder::new(req.decision, req.level == 3);
    rec.only = req.iteration;
    let cancel = Cancel::new();
    let mut rng = SplitMix64::new(block.seed);
    Pool::run_inline(|scratch: &mut Scratch, par: &TaskCx<'_, Scratch>| {
        let mut cx = AgentCx {
            scratch,
            par,
            cancel: &cancel,
        };
        gcg_ai_reference::search(st, d.player, cfg, weights, &mut rng, &mut cx, &mut rec)
    })
    .map_err(|e| format!("the Rust search failed: {}: {e:?}", e.py_class()))?;
    Ok((rec.iters, rec.applies))
}

fn first_iter_difference(py: &IterRec, rs: &IterRec) -> Option<(String, String, String)> {
    let (a, b) = (&py.iteration, &rs.iteration);
    let hex = crate::floathex::to_hex;
    let fields: [(&str, String, String); 12] = [
        ("child", a.child.to_string(), b.child.to_string()),
        ("k", a.visit.to_string(), b.visit.to_string()),
        ("fresh", a.fresh.to_string(), b.fresh.to_string()),
        ("path_len", a.path_len.to_string(), b.path_len.to_string()),
        (
            "applies_walk",
            a.applies_walk.to_string(),
            b.applies_walk.to_string(),
        ),
        (
            "applies_rollout",
            a.applies_rollout.to_string(),
            b.applies_rollout.to_string(),
        ),
        ("world16", py.world16.clone(), rs.world16.clone()),
        ("leaf", hex(a.leaf), hex(b.leaf)),
        ("terminal", a.terminal.to_string(), b.terminal.to_string()),
        ("total_before", hex(a.total_before), hex(b.total_before)),
        ("total_after", hex(a.total_after), hex(b.total_after)),
        ("n", a.n.to_string(), b.n.to_string()),
    ];
    fields
        .into_iter()
        .find(|(_, p, r)| p != r)
        .map(|(f, p, r)| (f.to_owned(), p, r))
}

/// The drill-down report.
///
/// # Errors
/// The trace, decision or search does not exist, or a side could not run.
pub fn trace_search(repo: &Repo, req: &Request<'_>) -> Result<(Vec<String>, bool), String> {
    let found = find_trace(repo, req.tier, req.file, req.id)?;
    if decision(&found.trace, req.decision)?
        .agent
        .as_ref()
        .is_none_or(|a| a.iterations.is_none())
    {
        return Err(format!(
            "{}: decision {} has no recorded search",
            req.id, req.decision
        ));
    }
    let (py_iters, py_applies, origin) = python_records(repo, &found.trace, req)?;
    let (rs_iters, rs_applies) = rust_records(&found.trace, req)?;
    let mut lines = vec![format!(
        "trace-search {} decision {} level {} ({} python iterations, {origin}; {} rust)",
        req.id,
        req.decision,
        req.level,
        py_iters.len(),
        rs_iters.len()
    )];
    let first = py_iters
        .iter()
        .zip(&rs_iters)
        .find_map(|(p, r)| first_iter_difference(p, r).map(|d| (p, d)));
    let Some((p, (field, pv, rv))) = first else {
        if py_iters.len() == rs_iters.len() && py_applies == rs_applies {
            lines.push(format!(
                "  identical: {} iterations, {} applies",
                py_iters.len(),
                py_applies.len()
            ));
            return Ok((lines, true));
        }
        if py_iters.len() != rs_iters.len() {
            lines.push(format!(
                "  iteration count differs: python {} rust {}",
                py_iters.len(),
                rs_iters.len()
            ));
        }
        push_apply_difference(&mut lines, &py_applies, &rs_applies, None);
        return Ok((lines, false));
    };
    let n = p.iteration.n;
    lines.push(format!("  first divergent iteration {n}"));
    lines.push(format!("    field       {field}"));
    lines.push(format!("    python      {pv}"));
    lines.push(format!("    rust        {rv}"));
    if req.level == 3 {
        push_apply_difference(&mut lines, &py_applies, &rs_applies, Some(n));
    } else {
        lines.push(format!(
            "    applies     gcg-diff trace-search {} {} --level 3 --iteration {n}",
            req.id, req.decision
        ));
    }
    lines.push(format!(
        "    state       gcg-diff explain {} {}",
        req.id, req.decision
    ));
    Ok((lines, false))
}

fn push_apply_difference(
    lines: &mut Vec<String>,
    py: &[ApplyTraceRec],
    rs: &[ApplyTraceRec],
    n: Option<u32>,
) {
    let of = |v: &[ApplyTraceRec]| -> Vec<ApplyTraceRec> {
        v.iter()
            .filter(|a| n.is_none_or(|k| a.n == k))
            .cloned()
            .collect()
    };
    let (py, rs) = (of(py), of(rs));
    match py.iter().zip(&rs).find(|(a, b)| a != b) {
        Some((a, b)) => {
            lines.push(format!("  first divergent apply {}/{}", a.n, a.j));
            lines.push(format!(
                "    python      {} -> {}",
                action_display(&a.action),
                a.after16
            ));
            lines.push(format!(
                "    rust        {} -> {}",
                action_display(&b.action),
                b.after16
            ));
        }
        None if py.len() != rs.len() => lines.push(format!(
            "  apply count differs: python {} rust {}",
            py.len(),
            rs.len()
        )),
        None => {}
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo() -> Repo {
        Repo {
            root: std::path::PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/../..")),
        }
    }

    const ACCEPTANCE: &str = "search/acceptance/standard/4242";

    #[test]
    fn stored_level_two_records_are_used_offline() {
        let found = find_trace(&repo(), 1, None, ACCEPTANCE).expect("the acceptance trace");
        let req = Request {
            tier: 1,
            file: None,
            id: ACCEPTANCE,
            decision: 4,
            level: 2,
            iteration: None,
        };
        let (iters, applies, origin) =
            python_records(&repo(), &found.trace, &req).expect("stored records");
        assert_eq!(
            (iters.len(), applies.len(), origin),
            (160, 0, "stored in the trace")
        );
        let one = Request {
            iteration: Some(7),
            ..req
        };
        let (iters, _, _) = python_records(&repo(), &found.trace, &one).expect("stored");
        assert_eq!(iters.len(), 1);
        assert_eq!(iters[0].iteration.n, 7);
    }

    #[test]
    fn the_first_differing_iteration_field_is_named() {
        let found = find_trace(&repo(), 1, None, ACCEPTANCE).expect("the acceptance trace");
        let it = found
            .trace
            .records
            .iter()
            .find_map(|r| match r {
                Record::Iter(it) => Some(it.clone()),
                _ => None,
            })
            .expect("an iteration");
        assert_eq!(first_iter_difference(&it, &it), None);
        let mut other = it.clone();
        other.iteration.total_after = f64::from_bits(other.iteration.total_after.to_bits() + 1);
        let (field, _, _) = first_iter_difference(&it, &other).expect("differs");
        assert_eq!(field, "total_after");
        other.world16 = "0000000000000000".to_owned();
        assert_eq!(
            first_iter_difference(&it, &other).map(|d| d.0),
            Some("world16".to_owned())
        );
    }
}
