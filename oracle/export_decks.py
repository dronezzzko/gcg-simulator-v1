"""Export the deck sets that ``gcg-eval`` embeds (docs/dev/PLAN.md §2.4, §10.4 F).

Writes ``crates/gcg-eval/decks/<set>-<name>.txt`` for the two deck sets that Python's
``ai/compare.py`` resolves by name (``DECK_SETS``, ``compare.py:58``):

- ``tests``: ``tests/ai/decks.py`` ``DECKS`` (``FEDERATION_DECK``, ``SEED_DECK``), the AI test
  decks of ``tests/slow/test_ai_strength.py``;
- ``tuning``: ``gcg_sim.ai.tuning.TUNING_DECKS`` (Zeon, Wing, Tekkadan; ``tuning.py:89-93``).

Each file is a deck file in the packaged format (``docs/DECK_FORMAT.md``): a comment header
naming its source, then one ``<count> <card_number> <name>`` line per card number in the
DeckList's order. The exporter asserts that ``to_decklist(parse_deck(text, name=stem))`` is
exactly the Python ``DeckList`` (same card numbers in the same order), so the Rust loader,
which reimplements ``parse_deck`` and ``to_decklist`` (gcg-data), rebuilds the same decks.

    uv run python oracle/export_decks.py [--check]
"""

from __future__ import annotations

import argparse
import importlib
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import cast

from gcg_sim.ai.tuning import TUNING_DECKS
from gcg_sim.cards.db import get_card_db
from gcg_sim.deck import parse_deck, to_decklist
from gcg_sim.engine.game import DeckList

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "crates" / "gcg-eval" / "decks"
GENERATED = "Generated by oracle/export_decks.py from the Python reference; do not edit."

# (set, deck names in the set's order). gcg-eval's decks.rs embeds the files in this order.
SET_NAMES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("tests", ("federation", "seed")),
    ("tuning", ("zeon", "wing", "tekkadan")),
)
SOURCES = {
    ("tests", "federation"): "tests/ai/decks.py FEDERATION_DECK (DECKS[0])",
    ("tests", "seed"): "tests/ai/decks.py SEED_DECK (DECKS[1])",
    ("tuning", "zeon"): "src/gcg_sim/ai/tuning.py TUNING_DECKS[0] (ZEON_COUNTS)",
    ("tuning", "wing"): "src/gcg_sim/ai/tuning.py TUNING_DECKS[1] (WING_COUNTS)",
    ("tuning", "tekkadan"): "src/gcg_sim/ai/tuning.py TUNING_DECKS[2] (TEKKADAN_COUNTS)",
}


def test_decks() -> tuple[DeckList, ...]:
    """``tests/ai/decks.py`` ``DECKS`` (read-only import of the reference's test decks)."""
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    module = importlib.import_module("tests.ai.decks")
    return cast(tuple[DeckList, ...], module.DECKS)


def runs(numbers: Sequence[str]) -> list[tuple[str, int]]:
    """Consecutive equal card numbers as ``(number, count)``, in order."""
    out: list[tuple[str, int]] = []
    for n in numbers:
        if out and out[-1][0] == n:
            out[-1] = (n, out[-1][1] + 1)
        else:
            out.append((n, 1))
    return out


def deck_text(set_name: str, name: str, deck: DeckList) -> str:
    db = get_card_db()
    lines = [
        f"# gcg-eval deck set {set_name!r}, deck {name!r}: {SOURCES[(set_name, name)]}.",
        f"# {GENERATED}",
        "",
        f"# Main deck ({len(deck.main)})",
    ]
    lines += [f"{count} {n} {db[n].name}" for n, count in runs(deck.main)]
    lines += ["", f"# Resource deck ({len(deck.resources)})"]
    lines += [f"{count} {n} {db[n].name}" for n, count in runs(deck.resources)]
    return "\n".join(lines) + "\n"


def build() -> dict[str, bytes]:
    sets: dict[str, tuple[DeckList, ...]] = {"tests": test_decks(), "tuning": TUNING_DECKS}
    files: dict[str, bytes] = {}
    for set_name, names in SET_NAMES:
        decks = sets[set_name]
        if len(decks) != len(names):
            raise SystemExit(f"{set_name}: {len(decks)} decks, expected {len(names)}")
        for name, deck in zip(names, decks, strict=True):
            stem = f"{set_name}-{name}"
            text = deck_text(set_name, name, deck)
            back = to_decklist(parse_deck(text, name=stem))
            if back != deck:
                raise SystemExit(f"{stem}: the deck file does not parse back to the DeckList")
            files[f"{stem}.txt"] = text.encode("utf-8")
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the committed files are stale")
    args = ap.parse_args()
    files = build()
    existing = {p.name: p for p in sorted(OUT.glob("*.txt"))} if OUT.exists() else {}
    if args.check:
        stale = sorted(
            name
            for name in set(files) | set(existing)
            if name not in files
            or name not in existing
            or existing[name].read_bytes() != files[name]
        )
        if stale:
            print(
                f"{OUT} is stale ({len(stale)} files, first {stale[0]}); run without --check",
                file=sys.stderr,
            )
            return 1
        print(f"{OUT} is current ({len(files)} files)")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, path in existing.items():
        if name not in files:
            path.unlink()
    for name, data in files.items():
        (OUT / name).write_bytes(data)
    print(f"wrote {len(files)} files to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
